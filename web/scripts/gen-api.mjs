// Generate src/api/schema.d.ts from the backend OpenAPI document.
// Usage: npm run gen:api [-- <url>]   (or set OPENAPI_URL)
// If the backend is not reachable, exit with a clear message and leave the
// existing schema.d.ts untouched so the build keeps working.
import { rename, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(here, '../src/api/schema.d.ts');

const explicit = process.argv[2] || process.env.OPENAPI_URL;
const candidates = explicit
  ? [explicit]
  : ['http://localhost:8000/api/v1/openapi.json', 'http://localhost:8000/openapi.json'];

async function fetchSpec(url) {
  const res = await fetch(url, { signal: AbortSignal.timeout(5000) });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  return res.json();
}

let spec;
let usedUrl;
const failures = [];
for (const url of candidates) {
  try {
    spec = await fetchSpec(url);
    usedUrl = url;
    break;
  } catch (err) {
    failures.push(`  - ${url}: ${err.cause?.code ?? err.message}`);
  }
}

if (!spec) {
  console.error(
    [
      'gen:api: không lấy được OpenAPI từ backend.',
      ...failures,
      '',
      'Cách xử lý:',
      '  1. Chạy backend: cd backend && uv run uvicorn app.main:app --reload --port 8000',
      '  2. Hoặc chỉ định URL: OPENAPI_URL=http://host:port/api/v1/openapi.json npm run gen:api',
      '',
      'Chưa đổi gì: src/api/schema.d.ts hiện tại (bản viết tay theo docs/dev-plan/08-api.md) được giữ nguyên,',
      'nên build và typecheck vẫn chạy được.',
    ].join('\n'),
  );
  process.exit(1);
}

const ast = await openapiTS(spec);
const header = `// Generated by \`npm run gen:api\` from ${usedUrl}. Do not edit by hand.\n\n`;
const tmp = `${outFile}.tmp`;
await writeFile(tmp, header + astToString(ast), 'utf8');
await rename(tmp, outFile);
console.log(`gen:api: đã ghi ${outFile} từ ${usedUrl}`);
console.log('Nhớ chạy `npm run typecheck`: nếu tên schema của backend khác bản tạm, sửa alias trong src/api/types.ts.');
